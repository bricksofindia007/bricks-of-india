const RB = /^https:\/\/cdn\.rebrickable\.com\/media\/(?:thumbs\/)?sets\/(.+?\.(?:jpg|jpeg|png))(?:\/\d+x\d+p\.jpg)?$/i;
const BS = /^https:\/\/images\.brickset\.com\/sets\/images\/(.+)\.jpg$/i;

/** True for an outside image URL known not to exist. */
export function isKnownMissingImage(url: string | null | undefined): boolean {
  if (!url) return false;
  const rb = url.match(RB);
  if (rb) return REBRICKABLE.has(rb[1]);
  const bs = url.match(BS);
  return bs ? BRICKSET.has(bs[1]) : false;
}
